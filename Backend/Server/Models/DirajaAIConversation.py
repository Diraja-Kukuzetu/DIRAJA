
from datetime import datetime, timedelta
import uuid

from app import db


def now_eat():
    """Return naive East African Time (UTC+3), consistent with existing models."""
    return datetime.utcnow() + timedelta(hours=3)


class DirajaAIConversation(db.Model):
    __tablename__ = "diraja_ai_conversations"

    conversation_id = db.Column(
        db.Integer,
        primary_key=True,
        autoincrement=True
    )

    # The manager who owns this conversation.
    user_id = db.Column(
        db.Integer,
        db.ForeignKey("users.users_id"),
        nullable=False,
        index=True
    )

    # Optional shop context for this conversation.
    shop_id = db.Column(
        db.Integer,
        db.ForeignKey("shops.shops_id"),
        nullable=True,
        index=True
    )

    title = db.Column(
        db.String(255),
        nullable=True
    )

    channel = db.Column(
        db.String(30),
        nullable=False,
        default="web"
    )

    status = db.Column(
        db.String(30),
        nullable=False,
        default="active",
        index=True
    )

    created_at = db.Column(
        db.DateTime,
        nullable=False,
        default=now_eat
    )

    updated_at = db.Column(
        db.DateTime,
        nullable=False,
        default=now_eat,
        onupdate=now_eat
    )

    last_message_at = db.Column(
        db.DateTime,
        nullable=True
    )

    # Relationships
    user = db.relationship(
        "Users",
        backref=db.backref("diraja_ai_conversations", lazy="dynamic")
    )

    shop = db.relationship(
        "Shops",
        backref=db.backref("diraja_ai_conversations", lazy="dynamic")
    )

    messages = db.relationship(
        "DirajaAIMessage",
        back_populates="conversation",
        cascade="all, delete-orphan",
        order_by="DirajaAIMessage.created_at",
        lazy="dynamic"
    )

    def to_dict(self, include_messages=False):
        data = {
            "conversation_id": self.conversation_id,
            "user_id": self.user_id,
            "shop_id": self.shop_id,
            "title": self.title,
            "channel": self.channel,
            "status": self.status,
            "created_at": self.created_at.isoformat() if self.created_at else None,
            "updated_at": self.updated_at.isoformat() if self.updated_at else None,
            "last_message_at": (
                self.last_message_at.isoformat()
                if self.last_message_at else None
            )
        }

        if include_messages:
            data["messages"] = [
                message.to_dict()
                for message in self.messages.order_by(
                    DirajaAIMessage.created_at.asc()
                ).all()
            ]

        return data


class DirajaAIMessage(db.Model):
    __tablename__ = "diraja_ai_messages"

    message_id = db.Column(
        db.Integer,
        primary_key=True,
        autoincrement=True
    )

    conversation_id = db.Column(
        db.Integer,
        db.ForeignKey(
            "diraja_ai_conversations.conversation_id",
            ondelete="CASCADE"
        ),
        nullable=False,
        index=True
    )

    # Same turn_id links one manager question to its AI answer.
    turn_id = db.Column(
        db.String(36),
        nullable=False,
        default=lambda: str(uuid.uuid4()),
        index=True
    )

    # user or assistant
    message_type = db.Column(
        db.String(20),
        nullable=False
    )

    content = db.Column(
        db.Text,
        nullable=False
    )

    # SQL generated by the AI, normally stored on assistant messages.
    sql_query = db.Column(
        db.Text,
        nullable=True
    )

    # Structured query results, columns, chart data, and other metadata.
    result_data = db.Column(
        db.JSON,
        nullable=True
    )

    model_name = db.Column(
        db.String(100),
        nullable=True
    )

    execution_status = db.Column(
        db.String(30),
        nullable=True
    )

    execution_time_ms = db.Column(
        db.Integer,
        nullable=True
    )

    error_message = db.Column(
        db.Text,
        nullable=True
    )

    # Reserved for later answer-quality evaluation.
    answer_score = db.Column(
        db.Float,
        nullable=True
    )

    score_feedback = db.Column(
        db.Text,
        nullable=True
    )

    scored_by_user_id = db.Column(
        db.Integer,
        db.ForeignKey("users.users_id"),
        nullable=True
    )

    scored_at = db.Column(
        db.DateTime,
        nullable=True
    )

    created_at = db.Column(
        db.DateTime,
        nullable=False,
        default=now_eat,
        index=True
    )

    conversation = db.relationship(
        "DirajaAIConversation",
        back_populates="messages"
    )

    scored_by = db.relationship(
        "Users",
        foreign_keys=[scored_by_user_id]
    )

    def to_dict(self):
        return {
            "message_id": self.message_id,
            "conversation_id": self.conversation_id,
            "turn_id": self.turn_id,
            "message_type": self.message_type,
            "content": self.content,
            "sql_query": self.sql_query,
            "result_data": self.result_data,
            "model_name": self.model_name,
            "execution_status": self.execution_status,
            "execution_time_ms": self.execution_time_ms,
            "answer_score": self.answer_score,
            "score_feedback": self.score_feedback,
            "created_at": self.created_at.isoformat() if self.created_at else None
        }
